# 1. 创建一个形状为 `[3, 4]` 的张量。
# 2. 取出第二行、最后一列以及第一行第二列。
# 3. 先在纸上预测 `sum(dim=0)` 和 `sum(dim=1)` 的值和形状，再运行核对。
# 4. 可选：读脚本中的矩阵乘法例子。`*` 是逐元素乘法，`@` 是矩阵乘法。
import torch 

print("PyTorch 版本：\n", torch.__version__)

x=torch.tensor([[1.0, 2.0, 3.0,4.0],[4.0, 5.0, 6.0,7.0],[7.0,8.0,9.0,10.0]])
print(x[1], x[:,-1], x[0, 1])
print(x.sum(dim=0), x.sum(dim=1))
w = torch.tensor([[1.0, 0.0], [0.0, 1.0], [1.0, 1.0], [2.0, 2.0]])
scores = x @ w
print("\n计算得到的示例得分：", scores)
