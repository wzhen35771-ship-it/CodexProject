"""第五天：人工候选的排序、构图、框匹配与召回率。

仅演示评估核心思想，采用连续坐标 IoU，不替代项目官方评估器。
"""

from collections import defaultdict


def 交并比(a, b):
    交宽 = max(0, min(a[2], b[2]) - max(a[0], b[0]))
    交高 = max(0, min(a[3], b[3]) - max(a[1], b[1]))
    交面积 = 交宽 * 交高
    a面积 = (a[2] - a[0]) * (a[3] - a[1])
    b面积 = (b[2] - b[0]) * (b[3] - b[1])
    并面积 = a面积 + b面积 - 交面积
    return 交面积 / 并面积 if 并面积 > 0 else 0.0


def 创建记录(三元组, 主体框, 客体框, 关系分数=1.0, 组="", 物体对=(0, 1),
             主体分数=1.0, 客体分数=1.0):
    return {
        "三元组": 三元组,
        "主体框": 主体框,
        "客体框": 客体框,
        "关系分数": 关系分数,
        "主体分数": 主体分数,
        "客体分数": 客体分数,
        "组": 组,
        "物体对": 物体对,
    }


def 综合得分(候选):
    return 候选["主体分数"] * 候选["关系分数"] * 候选["客体分数"]


def 匹配(候选, 真值):
    return (
        候选["三元组"] == 真值["三元组"]
        and 交并比(候选["主体框"], 真值["主体框"]) >= 0.5
        and 交并比(候选["客体框"], 真值["客体框"]) >= 0.5
    )


def 召回(候选列表, 真值列表, k):
    已找回 = set()
    排序候选 = sorted(候选列表, key=综合得分, reverse=True)
    for 候选 in 排序候选[:k]:
        for 编号, 真值 in enumerate(真值列表):
            if 匹配(候选, 真值):
                已找回.add(编号)
    if not 真值列表:
        raise ValueError("这个教学例子要求每帧至少有一条真值。")
    return len(已找回) / len(真值列表), 已找回


def 筛选候选(候选列表, 策略, 阈值=0.65):
    if 策略 == "无约束":
        return list(候选列表)
    按物体对和组 = defaultdict(list)
    for 候选 in 候选列表:
        按物体对和组[(候选["物体对"], 候选["组"])].append(候选)
    保留 = []
    for (_, 组), 组候选 in 按物体对和组.items():
        if 策略 == "有约束" or 组 == "注意":
            保留.append(max(组候选, key=lambda x: x["关系分数"]))
        elif 策略 == "半约束":
            保留.extend(x for x in 组候选 if x["关系分数"] > 阈值)
        else:
            raise ValueError("未知构图策略")
    return 保留


def main():
    人框 = [0, 0, 20, 60]
    杯框 = [30, 20, 40, 40]
    错杯框 = [70, 20, 80, 40]
    真值0 = [
        创建记录(("人", "看着", "杯子"), 人框, 杯框),
        创建记录(("人", "拿着", "杯子"), 人框, 杯框),
        创建记录(("杯子", "在前方", "人"), 杯框, 人框),
    ]
    候选0 = [
        创建记录(("人", "不看着", "杯子"), 人框, 杯框, 0.9, "注意"),
        创建记录(("人", "拿着", "杯子"), 人框, 杯框, 0.8, "接触"),
        创建记录(("杯子", "在前方", "人"), 杯框, 人框, 0.7, "空间"),
        创建记录(("人", "看着", "杯子"), 人框, 杯框, 0.6, "注意"),
    ]
    真值1 = [创建记录(("人", "拿着", "杯子"), 人框, 杯框)]
    候选1 = [
        创建记录(("人", "拿着", "杯子"), 人框, 错杯框, 0.95, "接触", (0, 1)),
        创建记录(("人", "拿着", "杯子"), 人框, 杯框, 0.75, "接触", (0, 2)),
    ]

    print("一、综合得分：0.9×0.8×0.7 =", round(0.9 * 0.8 * 0.7, 6))
    print("\n二、第0帧：按分数排序，再看前K个预测")
    for k in [1, 2, 3, 4]:
        得分, 已找回 = 召回(候选0, 真值0, k)
        print(f"R@{k}={得分:.4f}；找回的真值编号：{sorted(已找回)}")

    print("\n三、文字正确而框错误的候选")
    print("杯子框交并比：", 交并比(错杯框, 杯框))
    print("是否匹配：", 匹配(候选1[0], 真值1[0]))
    帧0召回, 找回0 = 召回(候选0, 真值0, 2)
    帧1召回, 找回1 = 召回(候选1, 真值1, 2)
    帧平均 = (帧0召回 + 帧1召回) / 2
    实例汇总 = (len(找回0) + len(找回1)) / (len(真值0) + len(真值1))
    print(f"第0帧 R@2={帧0召回:.4f}；第1帧 R@2={帧1召回:.4f}")
    print(f"帧平均={帧平均:.4f}；实例汇总={实例汇总:.4f}")

    print("\n四、构图策略改变保留候选")
    for 策略 in ["无约束", "有约束", "半约束"]:
        保留 = 筛选候选(候选0, 策略)
        print(策略, "保留：", [x["三元组"] for x in 保留])
        得分, _ = 召回(保留, 真值0, 4)
        print(f"使用全部保留候选时 R@4={得分:.4f}")

    print("\n五、重复预测不会把同一条真值计算两次")
    重复候选 = [候选0[1], 候选0[1]]
    得分, 已找回 = 召回(重复候选, 真值0, 2)
    print(f"两个重复‘拿着’预测：R@2={得分:.4f}；不同真值数={len(已找回)}")
    print("\n练习：将第0帧‘看着’分数改为0.95，先预测排序与有约束结果。")


if __name__ == "__main__":
    main()

